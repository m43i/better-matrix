//! The TypeScript types of everything that crosses the bridge, generated from the Rust types.
//!
//! They live in `packages/matrix-native/src/generated/types`. A test checks they are current;
//! `bun run bindings:types` writes them again after a change to the boundary.

use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

use crate::BridgeEvent;

/// Where the generated types live, from the repository root.
pub const TYPES_DIR: &str = "packages/matrix-native/src/generated/types";

/// The repository root, from this crate's manifest.
pub fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// Writes every type that crosses the bridge to `dir`, one file per type, and an `index.ts`
/// exporting them all.
pub fn export(dir: &Path) -> Result<(), String> {
    if dir.exists() {
        std::fs::remove_dir_all(dir).map_err(|e| e.to_string())?;
    }
    // JSON numbers: request IDs, timestamps and counts all fit in a double.
    let config = Config::new().with_large_int("number").with_out_dir(dir);
    matrix_core::Command::export_all(&config).map_err(|e| e.to_string())?;
    matrix_core::Event::export_all(&config).map_err(|e| e.to_string())?;
    BridgeEvent::export_all(&config).map_err(|e| e.to_string())?;
    // What the app's push task hands the bridge without the engine (`push::fetch_push`).
    matrix_core::PushTarget::export_all(&config).map_err(|e| e.to_string())?;
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .map_err(|e| e.to_string())?
        .filter_map(|entry| entry.ok()?.file_name().to_str()?.strip_suffix(".ts").map(str::to_owned))
        .collect();
    names.sort();
    let index: String =
        std::iter::once("// Generated by matrix-ffi (`bun run bindings:types`). Do not edit.\n".to_owned())
            .chain(names.iter().map(|name| format!("export type {{ {name} }} from \"./{name}\";\n")))
            .collect();
    std::fs::write(dir.join("index.ts"), index).map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Fails when the checked-in types differ from the Rust ones; set `UPDATE_BINDINGS=1` to
    /// write them instead.
    #[test]
    fn the_typescript_types_should_match_the_rust_types() {
        let checked_in = repository_root().join(TYPES_DIR);
        if std::env::var_os("UPDATE_BINDINGS").is_some() {
            export(&checked_in).unwrap();
            return;
        }
        let fresh = tempfile::tempdir().unwrap();
        export(fresh.path()).unwrap();
        let read = |dir: &Path| -> Vec<(String, String)> {
            let mut files: Vec<_> = std::fs::read_dir(dir)
                .map(|entries| {
                    entries
                        .filter_map(Result::ok)
                        .map(|e| {
                            let name = e.file_name().to_string_lossy().into_owned();
                            (name, std::fs::read_to_string(e.path()).unwrap_or_default())
                        })
                        .collect()
                })
                .unwrap_or_default();
            files.sort();
            files
        };
        assert!(read(fresh.path()) == read(&checked_in), "{TYPES_DIR} is out of date: run `bun run bindings:types`");
    }
}
