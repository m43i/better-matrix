export type IconName = keyof typeof icons;

export function Icon({
  name,
  size = 22,
  color,
  weight,
}: {
  name: IconName;
  size?: number;
  color: string;
  weight?: 'regular' | 'semibold' | 'bold';
}) {
  return (
    <SymbolView
      name={icons[name]}
      size={size}
      tintColor={color}
      weight={weight}
      style={{ width: size, height: size }}
    />
  );
}
